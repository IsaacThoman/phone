const canvas = document.querySelector("#display");
const context = canvas.getContext("2d", { alpha: false });
const form = document.querySelector("#message-form");
const input = document.querySelector("#message");
const status = document.querySelector("#status");
const counter = document.querySelector("#character-count");
const revision = document.querySelector("#revision");
const submitButton = form.querySelector("button");

context.imageSmoothingEnabled = false;

function wrapMessage(message) {
  const maxCharacters = Math.floor((DISPLAY_WIDTH + 1) / CHARACTER_ADVANCE);
  const lines = [];

  for (const paragraph of message.split("\n")) {
    if (!paragraph) {
      lines.push("");
      continue;
    }

    let remaining = paragraph;
    while (remaining.length > maxCharacters) {
      let breakAt = remaining.lastIndexOf(" ", maxCharacters);
      if (breakAt <= 0) breakAt = maxCharacters;
      lines.push(remaining.slice(0, breakAt).trimEnd());
      remaining = remaining.slice(breakAt).trimStart();
    }
    lines.push(remaining);
  }

  const maxLines = Math.floor((DISPLAY_HEIGHT - GLYPH_HEIGHT) / LINE_ADVANCE) + 1;
  return lines.slice(0, maxLines);
}

function drawMessage(message) {
  context.fillStyle = "#e8e5d8";
  context.fillRect(0, 0, DISPLAY_WIDTH, DISPLAY_HEIGHT);
  context.fillStyle = "#151512";

  const lines = wrapMessage(message);
  const blockHeight = GLYPH_HEIGHT + Math.max(0, lines.length - 1) * LINE_ADVANCE;
  const startY = Math.floor((DISPLAY_HEIGHT - blockHeight) / 2);

  lines.forEach((line, lineIndex) => {
    const lineWidth = line.length === 0 ? 0 : line.length * CHARACTER_ADVANCE - 1;
    let x = Math.floor((DISPLAY_WIDTH - lineWidth) / 2);
    const y = startY + lineIndex * LINE_ADVANCE;

    for (const character of line) {
      drawGlyph(character, x, y);
      x += CHARACTER_ADVANCE;
    }
  });
}

function drawGlyph(character, x, y) {
  const columns = FONT[character] ?? FONT["?"];
  for (let column = 0; column < GLYPH_WIDTH; column += 1) {
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      if ((columns[column] & (1 << row)) !== 0) context.fillRect(x + column, y + row, 1, 1);
    }
  }
}

async function loadMessage() {
  try {
    const response = await fetch("/api/message", { cache: "no-store" });
    if (!response.ok) throw new Error(`server returned ${response.status}`);
    const data = await response.json();
    input.value = data.message;
    revision.textContent = `REV ${data.revision}`;
    updatePreview();
  } catch (error) {
    status.textContent = `Could not load message: ${error.message}`;
    status.dataset.kind = "error";
  }
}

function updatePreview() {
  counter.textContent = `${input.value.length} / ${MAX_MESSAGE_LENGTH}`;
  drawMessage(input.value);
}

input.addEventListener("input", updatePreview);

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  submitButton.disabled = true;
  status.textContent = "Sending…";

  try {
    const response = await fetch("/api/message", {
      method: "PUT",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ message: input.value }),
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error ?? `server returned ${response.status}`);

    input.value = data.message;
    revision.textContent = `REV ${data.revision}`;
    updatePreview();
    status.textContent = "Message set. The device will receive it on its next poll.";
  } catch (error) {
    status.textContent = `Could not set message: ${error.message}`;
  } finally {
    submitButton.disabled = false;
  }
});

drawMessage("");
await loadMessage();
